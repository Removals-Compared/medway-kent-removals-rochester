-- ════════════════════════════════════════════════════════════
--  SEO Autopilot: audit fix proposals, reviewed before anything changes.
--  Idempotent; plain statements only (the "MKR SEO Migrate" workflow applies it).
-- ════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS seo_fixes (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch          text NOT NULL,
  path           text NOT NULL,
  kind           text NOT NULL CHECK (kind IN ('title','meta_description','sitemap_add','sitemap_remove','related_link')),
  before_text    text,
  after_text     text NOT NULL DEFAULT '',
  reason         text NOT NULL,
  source         text NOT NULL DEFAULT 'rule' CHECK (source IN ('rule','ai')),
  status         text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','approved','rejected','applied','conflict')),
  note           text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  decided_at     timestamptz,
  applied_at     timestamptz,
  applied_branch text,
  UNIQUE (batch, path, kind, after_text)
);
CREATE INDEX IF NOT EXISTS seo_fixes_status_idx ON seo_fixes (status, kind);
CREATE INDEX IF NOT EXISTS seo_fixes_path_idx ON seo_fixes (path, kind);
