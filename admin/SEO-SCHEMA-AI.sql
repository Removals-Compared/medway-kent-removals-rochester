-- The searches to check each month (kept to 20 or fewer, like BrightLocal's limit)
CREATE TABLE IF NOT EXISTS seo_ai_queries (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query      text NOT NULL UNIQUE,
  source     text NOT NULL DEFAULT 'manual' CHECK (source IN ('baseline','brightlocal','gsc','manual')),
  active     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- One row per search, engine and check run. Answers vary, so automatic checks
-- ask several times and store how many answers named / cited the business.
CREATE TABLE IF NOT EXISTS seo_ai_checks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checked_on  date NOT NULL,
  query       text NOT NULL,
  engine      text NOT NULL CHECK (engine IN ('claude','perplexity','chatgpt','google_aio','google_ai_mode','bing_copilot','bing_local','gemini','other')),
  method      text NOT NULL CHECK (method IN ('auto','manual','baseline')),
  result      text NOT NULL CHECK (result IN ('cited','named','not_named','error')),
  position    integer,
  samples     integer NOT NULL DEFAULT 1,
  hits_named  integer NOT NULL DEFAULT 0,
  hits_cited  integer NOT NULL DEFAULT 0,
  competitors text[] NOT NULL DEFAULT '{}',
  cited_urls  text[] NOT NULL DEFAULT '{}',
  excerpt     text,
  notes       text,
  created_by  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS seo_ai_checks_date_idx ON seo_ai_checks (checked_on DESC);
CREATE INDEX IF NOT EXISTS seo_ai_checks_q_idx ON seo_ai_checks (query, engine, checked_on DESC);

-- Rows read from a pasted BrightLocal "Local AI Visibility" page (one report per date)
CREATE TABLE IF NOT EXISTS seo_ai_bl_rows (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_date    date NOT NULL,
  kind           text NOT NULL CHECK (kind IN ('summary','platform','prompt','competitor','source')),
  name           text NOT NULL,
  visibility     numeric(6,2),
  mention_rate   numeric(6,2),
  share_of_voice numeric(6,2),
  avg_position   numeric(6,2),
  citations      integer,
  coverage_rate  numeric(6,2),
  cited_by       text,
  imported_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (report_date, kind, name)
);
CREATE INDEX IF NOT EXISTS seo_ai_bl_rows_date_idx ON seo_ai_bl_rows (report_date DESC, kind);
