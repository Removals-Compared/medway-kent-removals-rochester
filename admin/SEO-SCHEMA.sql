-- ════════════════════════════════════════════════════════════
--  Medway & Kent Removals — SEO Autopilot schema (Neon Postgres)
--  Idempotent: safe to run more than once in the Neon SQL editor.
--  Creates only new seo_* tables. Touches nothing that already exists.
--
--  Approval is enforced HERE, in the database, not just in app code:
--    * a revision's content hash is computed by the database
--    * revisions and approvals can never be edited or deleted
--    * an article cannot be set to approved / publishing / published unless
--      its revision has an 'approve' decision whose hash still matches
--    * an article with critical quality failures cannot be approved
--  So no API route, script, cron or workflow can skip the approval step.
-- ════════════════════════════════════════════════════════════

-- ── Settings (small key/value store: caps, counters, flags) ──
CREATE TABLE IF NOT EXISTS seo_settings (
  key        text PRIMARY KEY,
  value      jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ── Background jobs (audit, Search Console import, drafting, publishing) ──
CREATE TABLE IF NOT EXISTS seo_jobs (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type            text NOT NULL,
  status          text NOT NULL DEFAULT 'queued'
                  CHECK (status IN ('queued','running','succeeded','failed','cancelled')),
  payload         jsonb NOT NULL DEFAULT '{}'::jsonb,
  result          jsonb,
  attempts        integer NOT NULL DEFAULT 0,
  max_attempts    integer NOT NULL DEFAULT 3,
  idempotency_key text,
  last_error      text,
  requested_by    text,
  scheduled_at    timestamptz NOT NULL DEFAULT now(),
  started_at      timestamptz,
  finished_at     timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS seo_jobs_idem_uq ON seo_jobs (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS seo_jobs_status_idx ON seo_jobs (status, scheduled_at);
CREATE INDEX IF NOT EXISTS seo_jobs_type_idx ON seo_jobs (type, created_at DESC);

-- ── Page inventory (one row per crawled URL) ──
CREATE TABLE IF NOT EXISTS seo_pages (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url                text NOT NULL UNIQUE,
  path               text NOT NULL,
  page_type          text NOT NULL DEFAULT 'other',  -- home | service | town | post | hub | other
  status_code        integer,
  title              text,
  meta_description   text,
  canonical          text,
  robots             text,
  h1                 text,
  h1_count           integer,
  word_count         integer,
  images             integer,
  images_missing_alt integer,
  links_out          integer,
  links_in           integer,
  in_sitemap         boolean NOT NULL DEFAULT false,
  schema_types       text[] NOT NULL DEFAULT '{}',
  last_crawled       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS seo_pages_type_idx ON seo_pages (page_type);

-- ── Technical audit issues ──
CREATE TABLE IF NOT EXISTS seo_audit_issues (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url        text NOT NULL,
  type       text NOT NULL,
  issue_key  text NOT NULL DEFAULT '',
  severity   text NOT NULL CHECK (severity IN ('error','warn','info')),
  detail     text,
  status     text NOT NULL DEFAULT 'open' CHECK (status IN ('open','ignored','resolved')),
  run_id     bigint REFERENCES seo_jobs (id) ON DELETE SET NULL,
  first_seen timestamptz NOT NULL DEFAULT now(),
  last_seen  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (url, type, issue_key)
);
CREATE INDEX IF NOT EXISTS seo_audit_issues_status_idx ON seo_audit_issues (status, severity);

-- ── Search Console performance (real data only) ──
CREATE TABLE IF NOT EXISTS seo_search_metrics (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date        date NOT NULL,
  query       text NOT NULL,
  page        text NOT NULL DEFAULT '',
  clicks      integer NOT NULL DEFAULT 0,
  impressions integer NOT NULL DEFAULT 0,
  ctr         numeric(8,5),
  position    numeric(7,2),
  UNIQUE (date, query, page)
);
CREATE INDEX IF NOT EXISTS seo_search_metrics_date_idx ON seo_search_metrics (date);
CREATE INDEX IF NOT EXISTS seo_search_metrics_query_idx ON seo_search_metrics (query);
CREATE INDEX IF NOT EXISTS seo_search_metrics_page_idx ON seo_search_metrics (page);

-- ── Keywords (volume/difficulty stay NULL unless a real provider supplied them) ──
CREATE TABLE IF NOT EXISTS seo_keywords (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query       text NOT NULL UNIQUE,
  intent      text,
  target_url  text,
  cluster     text,
  priority    smallint NOT NULL DEFAULT 3 CHECK (priority BETWEEN 1 AND 5),
  source      text NOT NULL DEFAULT 'manual' CHECK (source IN ('gsc','manual','brightlocal','other')),
  volume      integer,
  difficulty  integer,
  status      text NOT NULL DEFAULT 'new' CHECK (status IN ('new','targeted','ignored')),
  notes       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ── Photo catalogue (own job photos + stock library). Nothing is usable until approved_for_web ──
CREATE TABLE IF NOT EXISTS seo_images (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file            text NOT NULL UNIQUE,
  source          text NOT NULL CHECK (source IN ('stock','own')),
  category        text,
  alt_text        text,
  description     text,
  tags            text[] NOT NULL DEFAULT '{}',
  width           integer,
  height          integer,
  bytes           integer,
  review_flags    text[] NOT NULL DEFAULT '{}',
  approved_for_web boolean NOT NULL DEFAULT false,
  used_count      integer NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now()
);

-- ── Articles ──
CREATE TABLE IF NOT EXISTS seo_articles (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                  text NOT NULL UNIQUE,
  title                 text NOT NULL,
  kind                  text NOT NULL DEFAULT 'post' CHECK (kind IN ('post','page_rewrite')),
  target_keyword        text,
  target_url            text,
  status                text NOT NULL DEFAULT 'planned' CHECK (status IN (
                          'planned','researching','drafting','quality_check','awaiting_approval',
                          'approved','publishing','published','rejected','needs_revision','failed','archived')),
  current_revision_id   bigint,
  published_revision_id bigint,
  quality_score         integer,
  quality_report        jsonb NOT NULL DEFAULT '{}'::jsonb,   -- must carry critical_count (integer)
  source                text NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','bot','scheduled_queue','opportunity')),
  scheduled_for         date,
  published_url         text,
  published_at          timestamptz,
  last_error            text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS seo_articles_status_idx ON seo_articles (status);
CREATE INDEX IF NOT EXISTS seo_articles_kw_idx ON seo_articles (target_keyword);

-- ── Immutable revisions. The database computes the content hash. ──
CREATE TABLE IF NOT EXISTS seo_article_revisions (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id       bigint NOT NULL REFERENCES seo_articles (id) ON DELETE CASCADE,
  version          integer NOT NULL,
  title            text NOT NULL,
  meta_description text,
  content          text NOT NULL,
  meta             jsonb NOT NULL DEFAULT '{}'::jsonb,
  image_id         bigint REFERENCES seo_images (id),
  content_hash     text NOT NULL DEFAULT '',
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (article_id, version)
);

-- ── Immutable approval decisions (one row per decision, never edited) ──
CREATE TABLE IF NOT EXISTS seo_approvals (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id    bigint NOT NULL REFERENCES seo_articles (id) ON DELETE CASCADE,
  revision_id   bigint NOT NULL REFERENCES seo_article_revisions (id) ON DELETE CASCADE,
  content_hash  text NOT NULL DEFAULT '',
  decision      text NOT NULL CHECK (decision IN ('approve','reject','request_changes')),
  reviewer      text NOT NULL,
  reviewer_role text NOT NULL CHECK (reviewer_role = 'admin'),
  reason        text,
  decided_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS seo_approvals_rev_idx ON seo_approvals (revision_id, decided_at DESC);

-- ── Local rank checks (BrightLocal, capped; see seo_settings) ──
CREATE TABLE IF NOT EXISTS seo_local_rankings (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checked_on     date NOT NULL,
  keyword        text NOT NULL,
  location       text NOT NULL,
  engine         text NOT NULL CHECK (engine IN ('google','bing')),
  pack_position  integer,
  organic_position integer,
  url            text,
  UNIQUE (checked_on, keyword, location, engine)
);

-- ── SEO activity trail ──
CREATE TABLE IF NOT EXISTS seo_activity (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at         timestamptz NOT NULL DEFAULT now(),
  actor      text NOT NULL,
  action     text NOT NULL,
  article_id bigint,
  detail     text
);
CREATE INDEX IF NOT EXISTS seo_activity_at_idx ON seo_activity (at DESC);

-- ════════════════════════════════════════════════════════════
--  Approval enforcement (triggers)
-- ════════════════════════════════════════════════════════════

-- The database, not the app, computes the revision hash.
CREATE OR REPLACE FUNCTION seo_revision_before_insert() RETURNS trigger AS $$
BEGIN
  NEW.content_hash := encode(sha256(convert_to(
    coalesce(NEW.title, '')            || E'\n' ||
    coalesce(NEW.meta_description, '') || E'\n' ||
    coalesce(NEW.content, '')          || E'\n' ||
    coalesce(NEW.meta::text, '{}')     || E'\n' ||
    coalesce(NEW.image_id::text, ''), 'UTF8')), 'hex');
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS seo_revision_before_insert_trg ON seo_article_revisions;
CREATE TRIGGER seo_revision_before_insert_trg BEFORE INSERT ON seo_article_revisions
  FOR EACH ROW EXECUTE FUNCTION seo_revision_before_insert();

-- Revisions and approvals are append-only. (Deleting a whole article still
-- cascades, because by then the parent row is already gone.)
CREATE OR REPLACE FUNCTION seo_block_edit() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM seo_articles WHERE id = OLD.article_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION '% rows are immutable (% blocked)', TG_TABLE_NAME, TG_OP;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS seo_revision_immutable_trg ON seo_article_revisions;
CREATE TRIGGER seo_revision_immutable_trg BEFORE UPDATE OR DELETE ON seo_article_revisions
  FOR EACH ROW EXECUTE FUNCTION seo_block_edit();

DROP TRIGGER IF EXISTS seo_approval_immutable_trg ON seo_approvals;
CREATE TRIGGER seo_approval_immutable_trg BEFORE UPDATE OR DELETE ON seo_approvals
  FOR EACH ROW EXECUTE FUNCTION seo_block_edit();

-- An approval is bound to the exact revision (and its hash) it was given on.
CREATE OR REPLACE FUNCTION seo_approval_before_insert() RETURNS trigger AS $$
DECLARE rev_hash text; rev_article bigint;
BEGIN
  SELECT content_hash, article_id INTO rev_hash, rev_article FROM seo_article_revisions WHERE id = NEW.revision_id;
  IF rev_hash IS NULL THEN RAISE EXCEPTION 'approval refers to a missing revision'; END IF;
  IF rev_article <> NEW.article_id THEN RAISE EXCEPTION 'revision does not belong to this article'; END IF;
  NEW.content_hash := rev_hash;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS seo_approval_before_insert_trg ON seo_approvals;
CREATE TRIGGER seo_approval_before_insert_trg BEFORE INSERT ON seo_approvals
  FOR EACH ROW EXECUTE FUNCTION seo_approval_before_insert();

-- The gate: no route, job or script can move an article into an approved /
-- publishing / published state without a matching approval of that revision.
CREATE OR REPLACE FUNCTION seo_article_gate() RETURNS trigger AS $$
DECLARE rev bigint; decision text; appr_hash text; rev_hash text;
BEGIN
  IF NEW.status IN ('approved','publishing','published') THEN
    rev := CASE WHEN NEW.status = 'published' THEN NEW.published_revision_id ELSE NEW.current_revision_id END;
    IF rev IS NULL THEN
      RAISE EXCEPTION 'article % cannot be % without a revision', NEW.slug, NEW.status;
    END IF;
    SELECT a.decision, a.content_hash, r.content_hash INTO decision, appr_hash, rev_hash
      FROM seo_approvals a JOIN seo_article_revisions r ON r.id = a.revision_id
     WHERE a.revision_id = rev AND a.article_id = NEW.id
     ORDER BY a.decided_at DESC, a.id DESC LIMIT 1;
    IF NOT FOUND OR decision <> 'approve' OR appr_hash <> rev_hash THEN
      RAISE EXCEPTION 'article % cannot be % without an approval of revision %', NEW.slug, NEW.status, rev;
    END IF;
    IF coalesce((NEW.quality_report->>'critical_count')::integer, 0) > 0 THEN
      RAISE EXCEPTION 'article % has critical quality failures and cannot be %', NEW.slug, NEW.status;
    END IF;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS seo_article_gate_trg ON seo_articles;
CREATE TRIGGER seo_article_gate_trg BEFORE INSERT OR UPDATE ON seo_articles
  FOR EACH ROW EXECUTE FUNCTION seo_article_gate();
